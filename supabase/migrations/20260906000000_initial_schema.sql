alter table seats     enable row level security;
alter table members   enable row level security;
alter table subjects  enable row level security;
alter table lessons   enable row level security;
alter table hw_checks enable row level security;
alter table tasks     enable row level security;
alter table goals     enable row level security;
alter table goal_log  enable row level security;
alter table notes     enable row level security;
alter table xp_events enable row level security;

-- seats: readable by members so the app can show who is invited. Never
-- writable from the browser — you add seats in the SQL editor.
drop policy if exists seats_read on seats;
create policy seats_read on seats for select using (is_member());

-- members: both of you can see each other. You can only edit yourself, so
-- neither can change the other's role, name, or preferences.
drop policy if exists members_read on members;
drop policy if exists members_self on members;
create policy members_read on members for select using (is_member());
create policy members_self on members for update using (id = auth.uid())
  with check (id = auth.uid());

-- Shared, but only you can claim your own work.
-- hw_checks, goal_log and xp_events are the record of what YOU did, so they
-- are writable only by their owner. Everything else either of you can edit,
-- which is what lets your partner set goals and write tasks for you.
do $$
declare t text;
begin
  foreach t in array array['subjects','lessons','tasks','goals'] loop
    execute format('drop policy if exists %1$s_all on %1$I', t);
    execute format('create policy %1$s_all on %1$I for all
                    using (is_member()) with check (is_member())', t);
  end loop;

  foreach t in array array['hw_checks','goal_log','xp_events'] loop
    execute format('drop policy if exists %1$s_read on %1$I', t);
    execute format('drop policy if exists %1$s_own on %1$I', t);
    execute format('create policy %1$s_read on %1$I for select using (is_member())', t);
    execute format('create policy %1$s_own on %1$I for all
                    using (owner_id = auth.uid()) with check (owner_id = auth.uid())', t);
  end loop;
end $$;

-- notes: you write as yourself; the person it is addressed to may mark it read.
drop policy if exists notes_read on notes;
drop policy if exists notes_write on notes;
drop policy if exists notes_mark on notes;
create policy notes_read  on notes for select using (is_member());
create policy notes_write on notes for all
  using (author_id = auth.uid()) with check (author_id = auth.uid());
create policy notes_mark  on notes for update
  using (target_id = auth.uid()) with check (target_id = auth.uid());
